// Settings DOM contracts; no browser/desktop automation and no live Telegram.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {createRequire} from "node:module";
const root = path.resolve(import.meta.dirname, "..");
const require = createRequire(path.join(root,"build/audit-js/package.json"));
const {JSDOM} = require("jsdom");
const dom = new JSDOM('<!doctype html><html lang="en"><body></body></html>',{url:"http://127.0.0.1:8132",runScripts:"outside-only"});
const w = dom.window;
w.PG_LANG = "en";
w.MemuSettingsKit = {link:o=>`<a data-sub="${o.sub}">${o.label}${o.value}</a>`,sub:o=>`<section id="${o.id}">${o.body}</section>`};
w.MemuModelPicker = {rows:()=>[{id:"chosen"},{id:"other"}],kindOf:()=>"chat",name:id=>"Name "+id,enhanceSelect:()=>{}};
let interval;
w.setInterval = fn => {interval=fn;return 1;}; w.clearInterval=()=>{};
const command = {name:"question",trigger:"!//question",enabled:true,kind:"question",prompt:"{question}",model:"",context_messages:30,output:"replace",allowed_users:[7],allowed_chats:[],max_per_hour:10,max_per_day:50,cooldown_seconds:5,max_input_chars:8000};
let state = {connected:false,configured:true,has_api_hash:true,has_proxy:false,account:{},flow:{phase:"idle"},last_error:"",config:{enabled:false,api_id:123,model:"chosen",commands_enabled:false,allow_writes:true,schedule_writes:false,max_media_mb:20,context_chars:32000,max_parallel:2,commands:[command]}};
const sent = [];
w.fetch = async (url, options={})=>{
  if(options.body){
    const data = JSON.parse(options.body); sent.push(data);
    if(data.action==="settings") state={...state,config:{...state.config,...data}};
    if(data.action==="phone") state={...state,flow:{phase:"code"}};
    if(data.action==="qr") state={...state,flow:{phase:"qr",url:"tg://login?token=test-only",expires:Date.now()/1000+30}};
  }
  return {ok:true,json:async()=>structuredClone(state)};
};
w.eval(fs.readFileSync(path.join(root,"app/pgstatic/telegram-use.js"),"utf8"));
w.document.body.innerHTML=w.MemuTelegramUse.listHtml()+w.MemuTelegramUse.subsHtml();
w.MemuTelegramUse.mount();
const tick=()=>new Promise(resolve=>setTimeout(resolve,5)); await tick();
const field=key=>w.document.querySelector(`#tgu-root > [data-tgu-field="${key}"], #tgu-root [data-tgu-field="${key}"]`);
assert.equal(field("api_id").value,"123");
assert.equal(field("model").value,"chosen");
assert.equal(field("api_hash").value,"");
field("api_hash").value="a".repeat(32);
field("proxy").value="socks5://localhost:1080";
w.document.querySelector('[data-tgu="add"]').click(); await tick();
assert.equal(w.document.querySelectorAll("[data-tgu-command]").length,2);
assert.equal(field("api_hash").value,"a".repeat(32),"editing commands preserves unsaved API hash");
assert.equal(field("proxy").value,"socks5://localhost:1080");
w.document.querySelector('[data-tgu="save"]').click(); await tick();
let saved=sent.findLast(x=>x.action==="settings");
assert.deepEqual(saved.commands[0].allowed_users,["7"]);
assert.equal(saved.model,"chosen");
assert.equal(saved.api_hash,"a".repeat(32));
const textarea=w.document.querySelector('[data-tgu-field="prompt"]'); textarea.value="unsaved prompt";
await interval();
assert.equal(textarea.value,"unsaved prompt","status polling does not replace the settings form");
field("phone").value="+79991234567";
w.document.querySelector('[data-tgu="phone"]').click(); await tick();
assert.equal(sent.findLast(x=>x.action==="phone").phone,"+79991234567");
assert.ok(field("code"));
w.document.querySelector('[data-tgu="qr"]').click(); await tick();
const img=w.document.querySelector(".tgu-qr");
assert.ok(img.src.startsWith("http://127.0.0.1:8132/api/pg/integrations/telegram-use/qr.png"));
assert.ok(!img.src.includes("token="),"QR is rendered locally without leaking login URL to a service");
assert.equal(sent.findLast(x=>x.action==="settings").enabled,true);
w.close();
console.log("PASS Telegram Use settings: models, secrets, command edits, persistence, auth and local QR");
