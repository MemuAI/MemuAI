def demo_image(width: int = 960, height: int = 540) -> str:
    """A fake "screen" for the screenshot mock: an editor with an error dialog."""
    from PIL import Image, ImageDraw
    img = Image.new("RGB", (width, height), (30, 32, 40))
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, width, 28], fill=(45, 48, 60))
    for i in range(14):
        d.rectangle([40, 50 + i * 26, 40 + (120 + (i * 53) % 380), 62 + i * 26], fill=(70 + i * 5, 110, 160 - i * 3))
    d.rectangle([300, 170, 700, 360], fill=(240, 240, 245), outline=(200, 60, 60), width=3)
    d.rectangle([300, 170, 700, 200], fill=(200, 60, 60))
    d.text((314, 178), "Error 0x80070005", fill=(255, 255, 255))
    d.text((314, 220), "Access is denied.", fill=(30, 30, 30))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=85)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):  # noqa: D401
        pass


def serve() -> tuple:
    handler = functools.partial(Quiet, directory=str(STATIC))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, f"http://127.0.0.1:{server.server_address[1]}"


