const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const requireAudit = createRequire(path.resolve('build/audit-js/package.json'));
const { JSDOM } = requireAudit('jsdom');
const source = fs.readFileSync(process.argv[2] || 'app/pgstatic/memu-ctxmenu.js', 'utf8');
const dom = new JSDOM('<!doctype html><body><button id="owner">Open</button><button id="outside">Outside</button></body>', { runScripts: 'outside-only', url: 'http://localhost/' });
const w = dom.window, frames = [], timers = [];
w.setTimeout = fn => { timers.push(fn); return timers.length; };
w.requestAnimationFrame = fn => { frames.push(fn); return frames.length; };
vm.runInContext(source, dom.getInternalVMContext());
const M = w.MemuCtxMenu, owner = w.document.getElementById('owner'), outside = w.document.getElementById('outside');
const pointer = node => node.dispatchEvent(new w.MouseEvent('pointerdown', { bubbles: true, cancelable: true, button: 0 }));
const reasons = [];
const options = () => ({ owner, items: [{ id: 'one', label: 'One' }], onClose: reason => reasons.push(reason) });
M.open(options());
pointer(outside);
assert.equal(M.current(), null, 'an immediate outside click must close the menu before any timer runs');
assert.equal(reasons.at(-1), 'outside');
assert.equal(timers.length, 0, 'binding outside input must not depend on a deferred timer');
const old = M.open(options());
const current = M.open(options());
assert.equal(old.close(), false, 'a replaced handle cannot close the current menu');
pointer(current.el.querySelector('button'));
assert(M.current(), 'input inside the current menu stays open');
pointer(outside);
assert.equal(M.current(), null, 'replacement also binds outside input synchronously');
w.addEventListener('pointerdown', () => M.open(options()), { capture: true, once: true });
pointer(owner);
assert(M.current(), 'a menu opened during pointerdown must survive the initiating event');
pointer(outside);
assert.equal(M.current(), null, 'the next independent pointerdown closes the menu');
const picked = [];
w.addEventListener('keydown', () => {
  M.open({ ...options(), keyboard: true, onPick: id => picked.push(id) });
  while (frames.length) frames.shift()();
}, { capture: true, once: true });
owner.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
assert(M.current(), 'opening with Enter must not immediately pick the first item');
assert.equal(picked.length, 0);
M.current().el.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
assert.deepEqual(picked, ['one']);
assert.equal(M.current(), null);
assert.equal(reasons.at(-1), 'pick');
M.open(options());
w.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }));
assert.equal(M.current(), null);
assert.equal(reasons.at(-1), 'escape');
console.log('PASS context menu: immediate outside input, replacement, inside input, opening pointer/keyboard events, selection and Escape');
dom.window.close();
