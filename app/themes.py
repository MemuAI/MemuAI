_CUSTOM_PREFIX = "custom:"
_SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,47}$")
MAX_THEME_BYTES = 256 * 1024
MAX_THEMES = 100

def normalize_mode(value: Any) -> str:
    return "light" if str(value or "") == "light" else "dark"

def normalize_accent(value: Any) -> str:
    return value if isinstance(value, str) and value in ACCENTS else DEFAULT_ACCENT

def variant(mode: str, variant_id: str) -> Optional[Dict[str, Any]]:
    return next((row for row in VARIANTS[normalize_mode(mode)] if row["id"] == variant_id), None)

def normalize_variant(mode: str, value: Any) -> str:
    """A built-in id of this mode, ``custom:<slug>`` or "" (the default)."""
    text = str(value or "") if isinstance(value, str) else ""
    if text.startswith(_CUSTOM_PREFIX):
        return text if _SLUG_RE.match(text[len(_CUSTOM_PREFIX):]) else ""
    return text if variant(mode, text) else ""

def variant_tokens(mode: str, variant_id: str = "") -> Dict[str, str]:
    """Complete token set of a built-in variant, syntax colours included."""
    mode = normalize_mode(mode)
    tokens = dict(_DARK_BASE if mode == "dark" else _LIGHT_BASE)
    row = variant(mode, variant_id) or VARIANTS[mode][0]
    tokens.update(row["tokens"])
    syntax = SYNTAX[row["syntax"]]
    tokens.update({f"--tok-{key}": syntax[key] for key in _SYNTAX_KEYS})
    return tokens

def _block(selector: str, tokens: Dict[str, str]) -> str:
    return selector + " {\n" + "".join(f"  {name}: {value};\n" for name, value in tokens.items()) + "}\n"

def theme_css() -> str:
    """The stylesheet served as ``/themes.css``: accents and every variant.

    Every selector is wrapped in ``:where()`` so built-in tokens carry zero
    specificity. A user theme's plain ``:root { --bg: ... }`` therefore always
    wins, even over the two-attribute block of the variant it extends.
    """
    parts = ["/* Generated by app/themes.py. Edit the catalogue there, not this output. */\n"]
    for name, row in ACCENTS.items():
        selector = f':where(:root[data-accent="{name}"])'
        if name == DEFAULT_ACCENT:
            selector = ":where(:root), " + selector
        parts.append(_block(selector, {"--accent-light": row["light"], "--accent-dark": row["dark"],
                                       "--accent2-light": row.get("light2", row["light"]),
                                       "--accent2-dark": row.get("dark2", row["dark"])}))
    for mode in ("dark", "light"):
        base = variant_tokens(mode, "")
        base_block = {"color-scheme": mode, **base,
                      "--accent": f"var(--accent-{mode})",
                      "--accent-2": f"var(--accent2-{mode})",
                      "--accent-soft": f"color-mix(in srgb, var(--accent) {12 if mode == 'dark' else 8}%, transparent)"}
        parts.append(_block(f':where([data-theme="{mode}"])', base_block))
        for row in VARIANTS[mode][1:]:
            full = variant_tokens(mode, row["id"])
            changed = {key: value for key, value in full.items() if base.get(key) != value}
            parts.append(_block(f':where([data-theme="{mode}"][data-surface="{row["id"]}"])', changed))
    return "".join(parts)

def themes_dir() -> Path:
    from .pgdata import MEMU_DIR
    return Path(MEMU_DIR) / "themes"

def valid_slug(value: Any) -> bool:
    return isinstance(value, str) and bool(_SLUG_RE.match(value))

def slugify(name: str) -> str:
    table = str.maketrans({
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z",
        "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
        "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
        "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya"})
    slug = re.sub(r"[^a-z0-9]+", "-", str(name or "").lower().translate(table)).strip("-")
    return slug[:40].strip("-") or "theme"

_META_RE = re.compile(r"^\s*\*?\s*@([a-z]+)\s+(.+?)\s*$", re.M)

def parse_meta(css: str) -> Dict[str, str]:
    """Read ``@key value`` lines from the first comment of a theme file."""
    match = re.match(r"\s*/\*(.*?)\*/", css or "", re.S)
    meta: Dict[str, str] = {}
    if match:
        for key, value in _META_RE.findall(match.group(1)):
            if key in ("name", "base", "extends", "author", "description", "version") and key not in meta:
                meta[key] = value.strip()[:200]
    return meta

def strip_meta(css: str) -> str:
    match = re.match(r"\s*/\*(.*?)\*/\s*", css or "", re.S)
    if match and "@name" in match.group(1):
        return (css or "")[match.end():]
    return css or ""

def extract_tokens(css: str) -> Dict[str, str]:
    """Custom properties declared in the theme's ``:root`` blocks.

    Used to give a module page the right colours on first paint; the live
    page later receives the computed values from the host anyway.
    """
    tokens: Dict[str, str] = {}
    for body in re.findall(r"(?:^|[}\s]):root(?:\[[^\]]*\])*\s*\{([^{}]*)\}", strip_meta(css or "")):
        for name, value in re.findall(r"(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);?", body):
            tokens[name] = value.strip()
    return tokens

def compose(meta: Dict[str, Any], body: str) -> str:
    """Theme file text: a canonical header followed by the CSS body."""
    lines = ["/*"]
    for key in ("name", "base", "extends", "author", "version", "description"):
        value = re.sub(r"[\r\n*/]+", " ", str(meta.get(key) or "")).strip()
        if value:
            lines.append(f" * @{key} {value}")
    lines.append(" */")
    return "\n".join(lines) + "\n" + strip_meta(body).lstrip("\n")

def _describe(slug: str, css: str, source: Path) -> Dict[str, Any]:
    meta = parse_meta(css)
    mode = normalize_mode(meta.get("base") or "dark")
    extends = meta.get("extends") or ""
    if not variant(mode, extends):
        extends = ""
    preview = variant_tokens(mode, extends)
    preview.update(extract_tokens(css))
    return {
        "id": slug,
        "ref": _CUSTOM_PREFIX + slug,
        "name": meta.get("name") or slug,
        "base": mode,
        "extends": extends,
        "author": meta.get("author") or "",
        "description": meta.get("description") or "",
        "version": meta.get("version") or "",
        "css": css,
        "size": len(css.encode("utf-8")),
        "file": str(source),
        "preview": {key: preview.get(key, "") for key in
                    ("--bg", "--bg-deep", "--panel", "--panel-2", "--border", "--text", "--muted", "--accent")},
    }

def list_custom() -> List[Dict[str, Any]]:
    folder = themes_dir()
    if not folder.is_dir():
        return []
    rows: List[Dict[str, Any]] = []
    for path in sorted(folder.glob("*.css"))[:MAX_THEMES]:
        slug = path.stem.lower()
        if not valid_slug(slug) or path.stat().st_size > MAX_THEME_BYTES:
            continue
        try:
            rows.append(_describe(slug, path.read_text(encoding="utf-8", errors="replace"), path))
        except OSError:
            continue
    return rows

def get_custom(slug: str) -> Optional[Dict[str, Any]]:
    if not valid_slug(slug):
        return None
    path = themes_dir() / f"{slug}.css"
    if not path.is_file() or path.stat().st_size > MAX_THEME_BYTES:
        return None
    return _describe(slug, path.read_text(encoding="utf-8", errors="replace"), path)

def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temp = tempfile.mkstemp(prefix=".theme-", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temp, path)
    except BaseException:
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise

def save_custom(data: Dict[str, Any]) -> Dict[str, Any]:
    """Create or replace a user theme. Returns its description.

    ``data`` holds ``name``, ``base``, ``extends``, ``css`` and optionally the
    ``id`` of the theme being edited and ``author``/``description``.
    """
    css = str(data.get("css") or "")
    meta = parse_meta(css)
    name = str(data.get("name") or meta.get("name") or "").strip()[:80] or "Моя тема"
    mode = normalize_mode(data.get("base") or meta.get("base"))
    extends = str(data.get("extends") if data.get("extends") is not None else meta.get("extends") or "")
    if not variant(mode, extends):
        extends = ""
    slug = str(data.get("id") or "").strip().lower()
    folder = themes_dir()
    if not valid_slug(slug):
        base_slug = slugify(name)
        slug = base_slug
        counter = 2
        while (folder / f"{slug}.css").exists():
            slug = f"{base_slug}-{counter}"[:48]
            counter += 1
    if not (folder / f"{slug}.css").exists() and len(list_custom()) >= MAX_THEMES:
        raise ValueError(f"Не больше {MAX_THEMES} своих тем")
    header = {
        "name": name, "base": mode, "extends": extends,
        "author": str(data.get("author") if data.get("author") is not None else meta.get("author") or "")[:80],
        "version": str(data.get("version") if data.get("version") is not None else meta.get("version") or "")[:20],
        "description": str(data.get("description") if data.get("description") is not None
                           else meta.get("description") or "")[:200],
    }
    text = compose(header, css)
    if "</style" in text.lower():
        raise ValueError("В теме не может быть </style>")
    if len(text.encode("utf-8")) > MAX_THEME_BYTES:
        raise ValueError("Тема больше 256 КБ")
    path = folder / f"{slug}.css"
    _write_text(path, text)
    return _describe(slug, text, path)

def delete_custom(slug: str) -> bool:
    if not valid_slug(slug):
        raise ValueError("Некорректный идентификатор темы")
    path = themes_dir() / f"{slug}.css"
    if path.is_file():
        path.unlink()
        return True
    return False

def resolve_tokens(mode: str, variant_ref: str = "", accent: str = DEFAULT_ACCENT) -> Dict[str, str]:
    """Final token values for a mode, a variant (built-in or custom) and an accent."""
    mode = normalize_mode(mode)
    ref = normalize_variant(mode, variant_ref)
    custom = get_custom(ref[len(_CUSTOM_PREFIX):]) if ref.startswith(_CUSTOM_PREFIX) else None
    if custom and custom["base"] == mode:
        tokens = variant_tokens(mode, custom["extends"])
    else:
        custom = None
        tokens = variant_tokens(mode, ref)
    accent_value = ACCENTS[normalize_accent(accent)][mode]
    tokens["--accent"] = accent_value
    tokens["--accent-soft"] = f"color-mix(in srgb, {accent_value} 12%, transparent)"
    if custom:
        overrides = extract_tokens(custom["css"])

        tokens.update({key: value for key, value in overrides.items() if "var(" not in value})
    return tokens

def catalog() -> Dict[str, Any]:
    """Everything the appearance screen and the theme studio need.

    Names come in both languages so the UI can switch language without
    fetching the catalogue again.
    """
    return {
        "accents": [{"id": key, "ru": row["ru"], "en": row["en"], "light": row["light"], "dark": row["dark"],
                     "light2": row.get("light2", row["light"]), "dark2": row.get("dark2", row["dark"])}
                    for key, row in ACCENTS.items()],
        "variants": {
            mode: [{"id": row["id"], "ru": row["ru"], "en": row["en"],
                    "note_ru": row["note_ru"], "note_en": row["note_en"], "syntax": row["syntax"],
                    "tokens": variant_tokens(mode, row["id"]),
                    "preview": {key: value for key, value in variant_tokens(mode, row["id"]).items()
                                if not key.startswith("--tok-")}}
                   for row in VARIANTS[mode]]
            for mode in ("dark", "light")
        },
        "tokens": [{"name": row["name"], "group": row["group"], "ru": row["ru"], "en": row["en"]}
                   for row in TOKENS]
        + [{"name": f"--tok-{key}", "group": "syntax", "ru": key, "en": key} for key in _SYNTAX_KEYS],
        "semantic": [{"name": row["name"], "fallback": row["fallback"], "ru": row["ru"], "en": row["en"]}
                     for row in SEMANTIC_TOKENS],
        "custom": list_custom(),
        "folder": str(themes_dir()),
        "designs": [dict(row) for row in DESIGNS],
    }
