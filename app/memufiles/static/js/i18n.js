export function addStrings(en, ru) {
  for (const [dict, add] of [[EN, en], [RU, ru]]) for (const [k, v] of Object.entries(add || {})) if (!(k in dict)) dict[k] = v;
}
export function t(key, vars) {
  const dict = LANG === "en" ? EN : RU;
  let text = dict[key];
  if (text === undefined) text = (LANG === "en" ? RU : EN)[key];
  if (text === undefined) return key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return text;
}

