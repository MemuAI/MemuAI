def ui_for(util: Any, en: bool) -> Dict[str, Any]:
    """The presentation block one catalogue row carries (``row["ui"]``)."""
    hint = H.get(util.id, {})
    pick = 1 if en else 0
    out: Dict[str, Any] = {}
    label: Optional[Tuple[str, str]] = hint.get("l")
    if label:
        out["label"] = label[pick]
    if hint.get("l2"):
        out["label2"] = hint["l2"][pick]
    ex = hint.get("ex")
    if ex:
        out["examples"] = list(ex[pick] or ex[0])[:4]
    ex2 = hint.get("ex2")
    if ex2:
        out["examples2"] = list(ex2[pick] or ex2[0])[:4]
    exo = hint.get("exo")
    if exo:
        out["exopts"] = dict(exo[pick] or exo[0])
    if hint.get("size") == "line" or util.pick == "folder":
        out["size"] = "line"
    if hint.get("code"):
        out["code"] = True
    verb = hint.get("v") or VERB_BY_CAT.get(util.cat)
    if verb:
        out["verb"] = verb[pick]
    if hint.get("auto"):
        out["auto"] = True
    if util.id in TOP:
        out["top"] = TOP.index(util.id) + 1
    return out
